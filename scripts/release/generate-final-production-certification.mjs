import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { envValue, readReport, releaseVersion, root } from "./verification-utils.mjs";

const git = (...args) => {
  try { return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); }
  catch { return "unknown"; }
};
const predeployFile = path.join(root, "reports", "release-candidate", "PREDEPLOY_REPORT.json");
const predeploy = existsSync(predeployFile) ? JSON.parse(readFileSync(predeployFile, "utf8")) : { checks: [] };
const environment = readReport("PRODUCTION_ENV_VALIDATION_REPORT");
const counts = environment?.summary?.counts ?? {};
const failedGates = predeploy.checks.filter(({ status }) => status !== "PASS").map(({ id }) => id);
const decision = (counts.ERROR || counts.FAIL || failedGates.length) ? "NO GO" : "CONDITIONAL GO";
const manual = ["Customer ordering", "Owner", "Kitchen", "Waiter", "POS", "QR", "Payments", "Printers", "Android", "iPhone", "Tablet", "Browser QA", "Accessibility QA", "Hardware", "Stress testing", "Lighthouse", "Provider dashboards"];
const md = `# Final Production Certification

Generated: ${new Date().toISOString()}

| Field | Value |
| --- | --- |
| Base repository SHA | \`${git("rev-parse", "HEAD")}\` (pre-certification commit) |
| Branch | \`${git("rev-parse", "--abbrev-ref", "HEAD")}\` |
| Release version | \`${releaseVersion()}\` |
| Node version | \`${process.version}\` |
| Environment | \`${envValue("NEXT_PUBLIC_APP_ENV") || "not configured"}\` |
| Decision | **${decision}** |

## Health Results

Repository health contracts expose SHA, version, environment, build timestamp, Node runtime, configuration, database, Firebase, storage, queues, and providers as PASS/WARN/FAIL without secrets. Hosted \`/health/live\`, \`/health/ready\`, and \`/health/startup\` verification remains external.

## Validation Results

- Environment: PASS ${counts.PASS ?? 0}, WARN ${counts.WARNING ?? 0}, ERROR ${counts.ERROR ?? 0}, MANUAL ${counts.MANUAL ?? 0}.
- Predeploy blockers: ${failedGates.length ? failedGates.join(", ") : "none"}.
- Source-side typecheck, lint, build, analyze, audit, operational smoke, runtime profile, contrast, brand, and diff evidence are generated by the release workflow.

## Known Warnings

- Firebase/protobuf emits an upstream dynamic-dependency build warning.
- Optional integrations report WARN when intentionally unconfigured.
- Full request status/duration logging depends on Hostinger ingress/process logs in addition to application trace logging.

## External Dependencies

- Hostinger environment variables, restart policy, memory limits, TLS, compression, and process supervision.
- Firebase Console services, rules/index deployment, service account, and authorized domains.
- Payment, WhatsApp, Sentry, email, DNS, provider dashboard, browser, device, and hardware configuration.

## Manual Tasks

${manual.map((item) => `- [ ] ${item}`).join("\n")}

## Deployment Checklist

1. Configure the production environment and run \`npm run predeploy\` until it passes.
2. Confirm Hostinger Node 22.x, \`npm ci\`, \`npm run build\`, \`.next\`, and \`npm run start\`.
3. Confirm automatic restart, graceful termination window, memory limit, HTTPS compression, and cache policy in hPanel.
4. Deploy this SHA and verify release-info plus all health endpoints.
5. Complete every manual task above before public traffic.

## Rollback Checklist

1. Redeploy the previous certified SHA and its matching environment snapshot.
2. Preserve QR and payment-encryption secrets.
3. Disable newly enabled provider/feature flags.
4. Clear application/CDN caches and restart.
5. Verify release-info, health endpoints, ordering, authentication, and payment status.

## Support Checklist

1. Record request/correlation ID, timestamp, module, tenant, and safe reproduction steps.
2. Check Hostinger process/ingress logs and application structured JSON logs.
3. Check health component status and provider dashboards.
4. Escalate payment incidents with provider order/event IDs, never secrets.
5. Use rollback when health is FAIL or customer/payment integrity is uncertain.
`;
writeFileSync(path.join(root, "docs", "release", "FINAL_PRODUCTION_CERTIFICATION.md"), md);
console.log(`docs/release/FINAL_PRODUCTION_CERTIFICATION.md generated: ${decision}`);
process.exitCode = decision === "NO GO" ? 1 : 0;
